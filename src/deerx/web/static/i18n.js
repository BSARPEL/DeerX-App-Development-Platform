// Dil, sunucudaki `language` ayarindan gelir; ayar okunana kadar tarayicida
// saklanan son secim kullanilir, boylece sayfa Turkce/Ingilizce arasinda
// gozle gorulur sekilde ziplamaz.
let LANG = (() => {
  try {
    const saved = localStorage.getItem("deerx-lang");
    if (saved === "tr" || saved === "en") return saved;
  } catch { /* depolama kapali olabilir */ }
  return "tr";
})();

function setLanguage(lang) {
  if (lang !== "tr" && lang !== "en") return;
  LANG = lang;
  try { localStorage.setItem("deerx-lang", lang); } catch { /* onemsiz */ }
  document.documentElement.lang = lang;
}

function currentLanguage() {
  return LANG;
}

/** Ceviriyi doner. `{ad}` yer tutuculari `vars` ile doldurulur. */
function t(key, vars) {
  const table = I18N[LANG] || I18N.tr;
  let text = table[key];
  if (text === undefined) {
    // Sessizce bos donmek eksik ceviriyi gorunmez kilar; anahtari goster.
    text = I18N.tr[key];
    if (text === undefined) {
      console.warn(`[i18n] eksik anahtar: ${key}`);
      return key;
    }
  }
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
}

/** Sunucudan gelen alan adini cevirir; bilinmiyorsa oldugu gibi doner. */
function tv(group, value) {
  if (value === null || value === undefined || value === "") return "";
  const table = I18N[LANG] || I18N.tr;
  return table[`${group}.${value}`] ?? value;
}

/** `data-i18n` isaretli her elemani cevirir. */
function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.title = t(node.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  });
}
